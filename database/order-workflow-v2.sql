create or replace function public.create_material_request_v2(
  p_project_id integer,p_notes text default null,p_urgency text default 'normal',p_delivery_date date default null,
  p_supplier text default null,p_delivery_location text default null,p_items jsonb default '[]'::jsonb,p_requested_for uuid default null
) returns jsonb language plpgsql security definer set search_path to '' as $$
declare
  v_actor_id uuid:=auth.uid(); v_actor public.profiles%rowtype; v_receiver public.profiles%rowtype;
  v_project public.proyectos%rowtype; v_settings public.app_settings%rowtype; v_receiver_id uuid;
  v_requester_sequence integer; v_project_sequence integer; v_order_number text; v_document_name text;
  v_supplier text; v_delivery_location text; v_order_id integer; v_item_count integer;
begin
  if v_actor_id is null then raise exception using errcode='42501',message='Authentication required.'; end if;
  select * into v_actor from public.profiles where id=v_actor_id;
  if not found or v_actor.status<>'activo' or v_actor.role='store' then raise exception using errcode='42501',message='This user cannot create material requests.'; end if;
  if v_actor.role='encargado' then v_receiver_id:=v_actor_id; else v_receiver_id:=coalesce(p_requested_for,v_actor_id); end if;
  select * into v_receiver from public.profiles where id=v_receiver_id and status='activo';
  if not found or v_receiver.role='store' then raise exception using errcode='22023',message='Invalid receiver.'; end if;
  select * into v_project from public.proyectos where id=p_project_id and estado='activo';
  if not found then raise exception using errcode='22023',message='The selected project is not active.'; end if;
  if v_actor.role='supervisor' and not public.supervisor_has_project(p_project_id) then raise exception using errcode='42501',message='You are not assigned to this project.'; end if;
  if v_receiver.document_initials is null or btrim(v_receiver.document_initials)='' then raise exception using errcode='22023',message='Document initials are not configured for the receiver.'; end if;
  select * into v_settings from public.app_settings where id=1;
  if not found then raise exception using errcode='55000',message='Application settings are missing.'; end if;
  p_urgency:=lower(coalesce(nullif(btrim(p_urgency),''),'normal'));
  if p_urgency not in ('normal','urgent','critical') then raise exception using errcode='22023',message='Invalid urgency.'; end if;
  if p_items is null or jsonb_typeof(p_items)<>'array' or jsonb_array_length(p_items)=0 then raise exception using errcode='22023',message='At least one material is required.'; end if;
  if exists(select 1 from jsonb_array_elements(p_items) x where not(x?'material_id') or not(x?'cantidad') or coalesce(x->>'material_id','')!~'^[0-9]+$' or coalesce(x->>'cantidad','')!~'^[0-9]+([.][0-9]+)?$' or (x->>'cantidad')::numeric<=0) then raise exception using errcode='22023',message='One or more material lines are invalid.'; end if;
  if exists(select 1 from jsonb_array_elements(p_items) x group by (x->>'material_id')::integer having count(*)>1) then raise exception using errcode='22023',message='The same material cannot be added twice.'; end if;
  select count(*) into v_item_count from jsonb_array_elements(p_items) x join public.materiales m on m.id=(x->>'material_id')::integer;
  if v_item_count<>jsonb_array_length(p_items) then raise exception using errcode='23503',message='One or more materials no longer exist.'; end if;

  insert into public.requester_order_counters(user_id,next_number) values(v_receiver_id,1) on conflict(user_id) do nothing;
  select next_number into v_requester_sequence from public.requester_order_counters where user_id=v_receiver_id for update;
  insert into public.project_requester_counters(project_id,user_id,next_number) values(p_project_id,v_receiver_id,1) on conflict(project_id,user_id) do nothing;
  select next_number into v_project_sequence from public.project_requester_counters where project_id=p_project_id and user_id=v_receiver_id for update;

  v_order_number:=upper(btrim(v_settings.company_initials))||coalesce(v_settings.order_separator,'-')||upper(btrim(v_receiver.document_initials))||coalesce(v_settings.order_separator,'-')||v_requester_sequence::text;
  v_document_name:=coalesce(nullif(btrim(v_settings.document_title),''),'MATERIAL REQUEST')||coalesce(v_settings.document_separator,' - ')||upper(btrim(v_project.codigo))||coalesce(v_settings.document_separator,' - ')||upper(btrim(v_receiver.document_initials))||coalesce(v_settings.document_separator,' - ')||lpad(v_project_sequence::text,coalesce(v_settings.project_sequence_padding,2),'0');
  v_supplier:=coalesce(nullif(btrim(p_supplier),''),nullif(btrim(v_project.default_supplier),''),nullif(btrim(v_settings.default_supplier),''));
  v_delivery_location:=coalesce(nullif(btrim(p_delivery_location),''),nullif(btrim(v_project.default_delivery_location),''),nullif(btrim(v_settings.default_delivery_location),''));

  insert into public.pedidos(user_id,requested_for,created_by,created_by_name_snapshot,project_id,status,urgencia,delivery_date,notas,order_number,requester_sequence,document_name,project_sequence,company_initials_snapshot,requester_initials_snapshot,project_name_snapshot,project_code_snapshot,requested_by_name,requested_by_email,requested_by_position,requested_by_department,requested_by_employee_code,supplier,delivery_location)
  values(v_receiver_id,v_receiver_id,v_actor_id,v_actor.full_name,p_project_id,'pending',p_urgency,p_delivery_date,nullif(btrim(p_notes),''),v_order_number,v_requester_sequence,v_document_name,v_project_sequence,upper(btrim(v_settings.company_initials)),upper(btrim(v_receiver.document_initials)),v_project.nombre,v_project.codigo,v_receiver.full_name,v_receiver.email,v_receiver.position,v_receiver.department,v_receiver.employee_code,v_supplier,v_delivery_location)
  returning id into v_order_id;

  insert into public.pedido_items(pedido_id,material_id,cantidad,notas,line_number,material_code_snapshot,material_name_snapshot,description_snapshot,unit_snapshot,supplier,quantity_delivered,quantity_received,required_date,observation)
  select v_order_id,m.id,(x.value->>'cantidad')::numeric,coalesce(x.value->>'notas',''),x.ordinality::integer,m.id_material,m.nombre,m.descripcion,m.unidad_medida,coalesce(nullif(btrim(x.value->>'supplier'),''),v_supplier),0,0,coalesce(nullif(x.value->>'required_date','')::date,p_delivery_date),coalesce(nullif(btrim(x.value->>'observation'),''),nullif(btrim(x.value->>'notas'),''))
  from jsonb_array_elements(p_items) with ordinality x(value,ordinality) join public.materiales m on m.id=(x.value->>'material_id')::integer;

  update public.requester_order_counters set next_number=v_requester_sequence+1 where user_id=v_receiver_id;
  update public.project_requester_counters set next_number=v_project_sequence+1 where project_id=p_project_id and user_id=v_receiver_id;
  insert into public.order_activity(pedido_id,actor_id,action,details) values(v_order_id,v_actor_id,'created',jsonb_build_object('actor_name',v_actor.full_name,'message',coalesce(v_actor.full_name,'User')||' created the material request.'));
  return jsonb_build_object('id',v_order_id,'order_number',v_order_number,'document_name',v_document_name,'status','pending');
end;
$$;
grant execute on function public.create_material_request_v2(integer,text,text,date,text,text,jsonb,uuid) to authenticated;

-- Edit request before first dispatch ----------------------------------------
create or replace function public.update_material_request_v2(p_order_id integer,p_project_id integer,p_requested_for uuid,p_notes text,p_urgency text,p_delivery_date date,p_items jsonb)
returns jsonb language plpgsql security definer set search_path to '' as $$
declare v_actor public.profiles%rowtype; v_order public.pedidos%rowtype; v_allowed boolean:=false;
begin
  select * into v_actor from public.profiles where id=auth.uid() and status='activo';
  if not found then raise exception using errcode='42501',message='Active user required.'; end if;
  select * into v_order from public.pedidos where id=p_order_id for update;
  if not found then raise exception using errcode='P0002',message='Order not found.'; end if;
  if exists(select 1 from public.order_dispatches where pedido_id=p_order_id) then raise exception using errcode='22023',message='The order cannot be edited after Store has dispatched material.'; end if;
  if p_project_id<>v_order.project_id or p_requested_for<>v_order.user_id then raise exception using errcode='22023',message='Project and receiver cannot be changed after the order number has been assigned.'; end if;
  if v_actor.role='encargado' then v_allowed:=(v_order.user_id=auth.uid() and v_order.status='pending');
  elsif v_actor.role='supervisor' then v_allowed:=(v_order.status in ('pending','approved') and public.supervisor_has_project(v_order.project_id));
  elsif v_actor.role='admin' then v_allowed:=v_order.status in ('pending','approved'); end if;
  if not v_allowed then raise exception using errcode='42501',message='You cannot edit this order.'; end if;
  if p_items is null or jsonb_typeof(p_items)<>'array' or jsonb_array_length(p_items)=0 then raise exception using errcode='22023',message='At least one material is required.'; end if;
  update public.pedidos set urgencia=lower(coalesce(nullif(btrim(p_urgency),''),'normal')),delivery_date=p_delivery_date,notas=nullif(btrim(p_notes),'') where id=p_order_id;
  delete from public.pedido_items where pedido_id=p_order_id;
  insert into public.pedido_items(pedido_id,material_id,cantidad,notas,line_number,material_code_snapshot,material_name_snapshot,description_snapshot,unit_snapshot,quantity_delivered,quantity_received,required_date,observation)
  select p_order_id,m.id,(x.value->>'cantidad')::numeric,coalesce(x.value->>'notas',''),x.ordinality::integer,m.id_material,m.nombre,m.descripcion,m.unidad_medida,0,0,p_delivery_date,nullif(btrim(x.value->>'notas'),'')
  from jsonb_array_elements(p_items) with ordinality x(value,ordinality) join public.materiales m on m.id=(x.value->>'material_id')::integer;
  insert into public.order_activity(pedido_id,actor_id,action,details) values(p_order_id,auth.uid(),'updated',jsonb_build_object('actor_name',v_actor.full_name,'message',coalesce(v_actor.full_name,'User')||' edited the material request.'));
  return jsonb_build_object('id',p_order_id,'status',v_order.status);
end;
$$;
grant execute on function public.update_material_request_v2(integer,integer,uuid,text,text,date,jsonb) to authenticated;

-- Approval / rejection ------------------------------------------------------
create or replace function public.approve_material_request_v2(p_order_id integer)
returns void language plpgsql security definer set search_path to '' as $$
declare v_order public.pedidos%rowtype; v_actor public.profiles%rowtype;
begin
  select * into v_actor from public.profiles where id=auth.uid() and status='activo';
  select * into v_order from public.pedidos where id=p_order_id for update;
  if not found then raise exception using errcode='P0002',message='Order not found.'; end if;
  if not(v_actor.role='admin' or (v_actor.role='supervisor' and public.supervisor_has_project(v_order.project_id))) then raise exception using errcode='42501',message='Only the project supervisor or an administrator can approve this order.'; end if;
  if v_order.status<>'pending' then raise exception using errcode='22023',message='Only pending orders can be approved.'; end if;
  update public.pedidos set status='approved',approved_by=auth.uid(),approved_at=now() where id=p_order_id;
  insert into public.order_activity(pedido_id,actor_id,action,details) values(p_order_id,auth.uid(),'approved',jsonb_build_object('actor_name',v_actor.full_name,'message',coalesce(v_actor.full_name,'Supervisor')||' approved the order.'));
end;
$$;
grant execute on function public.approve_material_request_v2(integer) to authenticated;

create or replace function public.reject_material_request_v2(p_order_id integer,p_reason text default null)
returns void language plpgsql security definer set search_path to '' as $$
declare v_order public.pedidos%rowtype; v_actor public.profiles%rowtype;
begin
  select * into v_actor from public.profiles where id=auth.uid() and status='activo';
  select * into v_order from public.pedidos where id=p_order_id for update;
  if not found then raise exception using errcode='P0002',message='Order not found.'; end if;
  if not(v_actor.role='admin' or (v_actor.role='supervisor' and public.supervisor_has_project(v_order.project_id))) then raise exception using errcode='42501',message='Only the project supervisor or an administrator can reject this order.'; end if;
  if v_order.status not in ('pending','approved') or exists(select 1 from public.order_dispatches where pedido_id=p_order_id) then raise exception using errcode='22023',message='This order can no longer be rejected.'; end if;
  update public.pedidos set status='rejected',rejected_reason=nullif(btrim(p_reason),'') where id=p_order_id;
  insert into public.order_activity(pedido_id,actor_id,action,details) values(p_order_id,auth.uid(),'rejected',jsonb_build_object('actor_name',v_actor.full_name,'message',coalesce(v_actor.full_name,'Supervisor')||' rejected the order.','reason',p_reason));
end;
$$;
