create or replace function public.propose_alternative_v2(p_order_id integer,p_pedido_item_id integer,p_alternative_material_id integer,p_reason text default null)
returns bigint language plpgsql security definer set search_path to '' as $$
declare v_actor public.profiles%rowtype; v_order public.pedidos%rowtype; v_id bigint; v_alt_name text;
begin
  select * into v_actor from public.profiles where id=auth.uid() and status='activo';
  if not found or v_actor.role not in ('store','admin') then raise exception using errcode='42501',message='Only Store or an administrator can propose alternatives.'; end if;
  select * into v_order from public.pedidos where id=p_order_id;
  if not found or v_order.status not in ('approved','partial') then raise exception using errcode='22023',message='Alternatives can only be proposed for approved or partial orders.'; end if;
  if not exists(select 1 from public.pedido_items where id=p_pedido_item_id and pedido_id=p_order_id) then raise exception using errcode='22023',message='Invalid order item.'; end if;
  select nombre into v_alt_name from public.materiales where id=p_alternative_material_id;
  if not found then raise exception using errcode='23503',message='Alternative material not found.'; end if;
  update public.order_alternatives set status='rejected',decided_at=now(),decision_note='Superseded by newer proposal' where pedido_item_id=p_pedido_item_id and status='pending';
  insert into public.order_alternatives(pedido_id,pedido_item_id,alternative_material_id,proposed_by,reason) values(p_order_id,p_pedido_item_id,p_alternative_material_id,auth.uid(),nullif(btrim(p_reason),'')) returning id into v_id;
  insert into public.order_activity(pedido_id,actor_id,action,details) values(p_order_id,auth.uid(),'alternative_proposed',jsonb_build_object('actor_name',v_actor.full_name,'message','Store proposed alternative: '||v_alt_name));
  return v_id;
end;
$$;
grant execute on function public.propose_alternative_v2(integer,integer,integer,text) to authenticated;

create or replace function public.decide_alternative_v2(p_alternative_id bigint,p_decision text,p_note text default null)
returns void language plpgsql security definer set search_path to '' as $$
declare v_alt public.order_alternatives%rowtype; v_order public.pedidos%rowtype; v_actor public.profiles%rowtype; v_name text;
begin
  if p_decision not in ('approved','rejected') then raise exception using errcode='22023',message='Decision must be approved or rejected.'; end if;
  select * into v_actor from public.profiles where id=auth.uid() and status='activo';
  select * into v_alt from public.order_alternatives where id=p_alternative_id for update;
  if not found then raise exception using errcode='P0002',message='Alternative not found.'; end if;
  select * into v_order from public.pedidos where id=v_alt.pedido_id;
  if not(v_actor.role='admin' or (v_actor.role='supervisor' and public.supervisor_has_project(v_order.project_id))) then raise exception using errcode='42501',message='Only the project supervisor or an administrator can decide this alternative.'; end if;
  if v_alt.status<>'pending' then raise exception using errcode='22023',message='This alternative has already been decided.'; end if;
  update public.order_alternatives set status=p_decision,decided_by=auth.uid(),decision_note=nullif(btrim(p_note),''),decided_at=now() where id=p_alternative_id;
  select nombre into v_name from public.materiales where id=v_alt.alternative_material_id;
  insert into public.order_activity(pedido_id,actor_id,action,details) values(v_alt.pedido_id,auth.uid(),'alternative_'||p_decision,jsonb_build_object('actor_name',v_actor.full_name,'message',coalesce(v_actor.full_name,'Supervisor')||' '||p_decision||' alternative '||coalesce(v_name,'')));
end;
$$;
grant execute on function public.decide_alternative_v2(bigint,text,text) to authenticated;

-- Store dispatch ------------------------------------------------------------
create or replace function public.dispatch_material_request_v2(p_order_id integer,p_note text,p_items jsonb)
returns bigint language plpgsql security definer set search_path to '' as $$
declare v_actor public.profiles%rowtype; v_order public.pedidos%rowtype; v_dispatch_id bigint; v_line jsonb; v_item public.pedido_items%rowtype; v_qty numeric; v_actual_material integer; v_outstanding numeric;
begin
  select * into v_actor from public.profiles where id=auth.uid() and status='activo';
  if not found or v_actor.role not in ('store','admin') then raise exception using errcode='42501',message='Only Store or an administrator can dispatch materials.'; end if;
  select * into v_order from public.pedidos where id=p_order_id for update;
  if not found then raise exception using errcode='P0002',message='Order not found.'; end if;
  if v_order.status not in ('approved','partial') then raise exception using errcode='22023',message='This order is not ready for dispatch.'; end if;
  if p_items is null or jsonb_typeof(p_items)<>'array' or jsonb_array_length(p_items)=0 then raise exception using errcode='22023',message='At least one dispatch quantity is required.'; end if;
  if exists(select 1 from jsonb_array_elements(p_items) x group by (x->>'pedido_item_id')::integer having count(*)>1) then raise exception using errcode='22023',message='Each order item can appear only once in a dispatch.'; end if;
  insert into public.order_dispatches(pedido_id,dispatched_by,note) values(p_order_id,auth.uid(),nullif(btrim(p_note),'')) returning id into v_dispatch_id;
  for v_line in select value from jsonb_array_elements(p_items) loop
    select * into v_item from public.pedido_items where id=(v_line->>'pedido_item_id')::integer and pedido_id=p_order_id for update;
    if not found then raise exception using errcode='22023',message='Invalid dispatch item.'; end if;
    v_qty:=(v_line->>'quantity')::numeric;
    if v_qty<=0 then raise exception using errcode='22023',message='Dispatch quantities must be greater than zero.'; end if;
    v_outstanding:=greatest(0,v_item.cantidad-v_item.quantity_received);
    if v_qty>v_outstanding then raise exception using errcode='22023',message='Dispatch quantity exceeds outstanding requested quantity.'; end if;
    v_actual_material:=coalesce(nullif(v_line->>'material_id','')::integer,v_item.material_id);
    if v_actual_material<>v_item.material_id and not exists(select 1 from public.order_alternatives a where a.pedido_item_id=v_item.id and a.alternative_material_id=v_actual_material and a.status='approved') then raise exception using errcode='22023',message='The selected alternative has not been approved.'; end if;
    insert into public.order_dispatch_items(dispatch_id,pedido_item_id,material_id,quantity_dispatched) values(v_dispatch_id,v_item.id,v_actual_material,v_qty);
    update public.pedido_items set quantity_delivered=quantity_delivered+v_qty where id=v_item.id;
  end loop;
  update public.pedidos set status='awaiting_receipt' where id=p_order_id;
  insert into public.order_activity(pedido_id,actor_id,action,details) values(p_order_id,auth.uid(),'dispatched',jsonb_build_object('actor_name',v_actor.full_name,'message',coalesce(v_actor.full_name,'Store')||' dispatched materials.','dispatch_id',v_dispatch_id));
  return v_dispatch_id;
end;
$$;
grant execute on function public.dispatch_material_request_v2(integer,text,jsonb) to authenticated;

-- Worker / Supervisor receipt ----------------------------------------------
create or replace function public.confirm_dispatch_receipt_v2(p_dispatch_id bigint,p_items jsonb)
returns text language plpgsql security definer set search_path to '' as $$
declare v_actor public.profiles%rowtype; v_dispatch public.order_dispatches%rowtype; v_order public.pedidos%rowtype; v_line jsonb; v_di public.order_dispatch_items%rowtype; v_qty numeric; v_status text; v_all_complete boolean;
begin
  select * into v_actor from public.profiles where id=auth.uid() and status='activo';
  if not found or v_actor.role not in ('encargado','supervisor') then raise exception using errcode='42501',message='Only the receiving worker or project supervisor can confirm receipt.'; end if;
  select * into v_dispatch from public.order_dispatches where id=p_dispatch_id for update;
  if not found then raise exception using errcode='P0002',message='Dispatch not found.'; end if;
  if v_dispatch.receipt_confirmed_at is not null then raise exception using errcode='22023',message='This dispatch has already been confirmed.'; end if;
  select * into v_order from public.pedidos where id=v_dispatch.pedido_id for update;
  if v_actor.role='encargado' and v_order.user_id<>auth.uid() then raise exception using errcode='42501',message='Only the worker assigned to this request can confirm it.'; end if;
  if v_actor.role='supervisor' and not public.supervisor_has_project(v_order.project_id) then raise exception using errcode='42501',message='You are not assigned to this project.'; end if;
  if v_order.status<>'awaiting_receipt' then raise exception using errcode='22023',message='This order is not awaiting receipt.'; end if;
  if p_items is null or jsonb_typeof(p_items)<>'array' then raise exception using errcode='22023',message='Receipt lines are required.'; end if;
  if jsonb_array_length(p_items)<>(select count(*) from public.order_dispatch_items where dispatch_id=p_dispatch_id) then raise exception using errcode='22023',message='All dispatched lines must be confirmed together.'; end if;
  if exists(select 1 from jsonb_array_elements(p_items) x group by (x->>'dispatch_item_id')::bigint having count(*)>1) then raise exception using errcode='22023',message='A receipt line cannot be repeated.'; end if;
  for v_line in select value from jsonb_array_elements(p_items) loop
    select * into v_di from public.order_dispatch_items where id=(v_line->>'dispatch_item_id')::bigint and dispatch_id=p_dispatch_id for update;
    if not found then raise exception using errcode='22023',message='Invalid receipt line.'; end if;
    v_qty:=(v_line->>'quantity_received')::numeric;
    if v_qty<0 or v_qty>v_di.quantity_dispatched then raise exception using errcode='22023',message='Received quantity must be between zero and dispatched quantity.'; end if;
    update public.order_dispatch_items set quantity_received=v_qty,receipt_observation=nullif(btrim(v_line->>'observation'),''),received_by=auth.uid(),received_at=now() where id=v_di.id;
  end loop;
  update public.order_dispatches set receipt_confirmed_by=auth.uid(),receipt_confirmed_at=now() where id=p_dispatch_id;
  update public.pedido_items pi set quantity_received=coalesce((select sum(di.quantity_received) from public.order_dispatch_items di join public.order_dispatches d on d.id=di.dispatch_id where di.pedido_item_id=pi.id and d.receipt_confirmed_at is not null),0),received_by=auth.uid(),received_at=now() where pi.pedido_id=v_order.id;
  select bool_and(quantity_received>=cantidad) into v_all_complete from public.pedido_items where pedido_id=v_order.id;
  v_status:=case when coalesce(v_all_complete,false) then 'completed' else 'partial' end;
  update public.pedidos set status=v_status,receipt_confirmed_by=case when v_status='completed' then auth.uid() else receipt_confirmed_by end,receipt_confirmed_at=case when v_status='completed' then now() else receipt_confirmed_at end where id=v_order.id;
  insert into public.order_activity(pedido_id,actor_id,action,details) values(v_order.id,auth.uid(),'receipt_confirmed',jsonb_build_object('actor_name',v_actor.full_name,'message',coalesce(v_actor.full_name,'Receiver')||' confirmed the material receipt.','dispatch_id',p_dispatch_id,'result',v_status));
  if v_status='completed' then insert into public.order_activity(pedido_id,actor_id,action,details) values(v_order.id,auth.uid(),'completed',jsonb_build_object('actor_name',v_actor.full_name,'message','Order completed: all requested quantities have been received.')); end if;
  return v_status;
end;
$$;
grant execute on function public.confirm_dispatch_receipt_v2(bigint,jsonb) to authenticated;

